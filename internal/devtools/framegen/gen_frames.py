"""Generates themes/default/frames/<rarity>.svg: per-rarity ornaments layered
over the shared frame. Card coordinates are 722x1022; levels 1..5 add detail."""
import sys

W, H = 722, 1022
CX = W / 2

def sparkle(x, y, r, cls="sparkle"):
    return (f'<path class="{cls}" d="M{x},{y-r} Q{x},{y} {x+r},{y} Q{x},{y} {x},{y+r} '
            f'Q{x},{y} {x-r},{y} Q{x},{y} {x},{y-r} Z"/>')

def corner(level):
    parts = [
        '<polygon class="orn" points="0,30 30,0 86,0 74,12 36,12 12,36 12,74 0,86"/>',
        '<polygon class="stud" points="24,14 34,24 24,34 14,24"/>',
    ]
    if level >= 2:
        parts.append('<path class="orn-thin" d="M32,66 V42 L42,32 H66"/>')
    if level >= 3:
        parts.append(sparkle(52, 52, 8))
    if level >= 4:
        parts.append('<path class="orn-line" d="M5,118 C20,110 24,96 12,84"/>')
        parts.append('<path class="orn-line" d="M118,5 C110,20 96,24 84,12"/>')
    if level >= 5:
        parts.append('<polygon class="orn" points="0,128 12,142 0,156 -8,142"/>')
        parts.append('<polygon class="orn" points="128,0 142,12 156,0 142,-8"/>')
        parts.append(sparkle(-4, -4, 10))
    return "".join(parts)

def notch(level):
    parts = ['<polygon class="orn" points="-8,670 8,654 24,670 8,686"/>',
             '<polygon class="stud" points="8,663 15,670 8,677 1,670"/>']
    if level >= 3:
        parts.append('<path class="orn-thin" d="M30,670 H72"/>')
    return "".join(parts)

def side_accent(level):
    if level < 4:
        return ""
    return ('<polygon class="orn" points="10,300 22,320 10,340 -2,320"/>'
            '<polygon class="stud" points="10,313 14,320 10,327 6,320"/>')

def gem(level):
    t, r, b, l, c = (CX, 962), (CX + 30, 998), (CX, 1034), (CX - 30, 998), (CX, 998)
    pts = lambda *ps: " ".join(f"{x},{y}" for x, y in ps)
    parts = []
    if level >= 2:
        parts.append(f'<ellipse class="gem-glow" cx="{CX}" cy="998" rx="{24 + 6*level}" ry="{30 + 5*level}"/>')
    # flanking lines on the bottom band
    parts.append(f'<path class="orn-line" d="M{CX-74},1012 H{CX-40} M{CX+40},1012 H{CX+74}"/>')
    if level >= 4:
        parts.append(f'<path class="orn-line" d="M{CX-40},1010 C{CX-62},996 {CX-86},998 {CX-104},1012"/>')
        parts.append(f'<path class="orn-line" d="M{CX+40},1010 C{CX+62},996 {CX+86},998 {CX+104},1012"/>')
    if level >= 5:
        for dx in (-118, 118):
            parts.append(f'<polygon class="stud" points="{CX+dx},1007 {CX+dx+8},1015 {CX+dx},1023 {CX+dx-8},1015"/>')
    parts += [
        f'<polygon class="gem-base" points="{pts(t, r, b, l)}"/>',
        f'<polygon class="gem-left" points="{pts(t, c, l)}"/>',
        f'<polygon class="gem-top" points="{pts(t, r, c)}"/>',
        f'<polygon class="gem-right" points="{pts(r, b, c)}"/>',
        f'<polygon class="gem-low" points="{pts(b, l, c)}"/>',
        f'<polygon class="gem-shine" points="{pts((CX-9, 976), (CX-3, 970), (CX-5, 986))}"/>',
    ]
    if level >= 3:
        parts.append(sparkle(CX + 14, 972, 6))
    return "".join(parts)

def crest(level):
    if level == 4:
        return (f'<polygon class="orn" points="{CX-30},10 {CX},-6 {CX+30},10 {CX},26"/>'
                f'<polygon class="stud" points="{CX},2 {CX+8},10 {CX},18 {CX-8},10"/>')
    if level >= 5:
        return (f'<polygon class="orn" points="{CX-46},10 {CX-28},-6 {CX-14},4 {CX},-13 {CX+14},4 '
                f'{CX+28},-6 {CX+46},10 {CX+24},26 {CX-24},26"/>'
                f'<polygon class="stud" points="{CX},0 {CX+9},10 {CX},20 {CX-9},10"/>'
                + sparkle(CX - 60, -4, 6) + sparkle(CX + 60, -4, 6))
    return ""

def frame(level):
    c = corner(level)
    mirrored = lambda g: (f'<g>{g}</g><g transform="translate({W},0) scale(-1,1)">{g}</g>')
    body = (
        mirrored(c)
        + f'<g transform="translate(0,{H}) scale(1,-1)">{mirrored(c)}</g>'
        + mirrored(notch(level))
        + mirrored(side_accent(level))
        + crest(level)
        + gem(level)
    )
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" aria-hidden="true">'
            f'<!-- rarity ornaments, level {level}; generated by internal/devtools/framegen, see docs/TEMAS.md -->{body}</svg>\n')

out = sys.argv[1]
for level, rarity in enumerate(["common", "uncommon", "rare", "epic", "legendary"], start=1):
    with open(f"{out}/{rarity}.svg", "w") as f:
        f.write(frame(level))
